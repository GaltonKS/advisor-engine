"""The QuickBooks CSV reader (advisor_engine.books), ported from the FIS pilot skeleton.

Two halves:

* The skeleton's own tests (test/upload.test.js), ported one for one. The CSV exports
  they read were generated by the skeleton's test/qb-fixtures.js and committed under
  tests/fixtures/qb/ (see the README there); where a JS test edits an export's text, the
  Python test makes the same edit to the committed file.
* Parity: for every committed export, Python's read (and apply) must equal what the JS
  reader produced for it, exactly, after a JSON round trip.

Parts of the JS tests that run the skeleton's model (FIS.build / FIS.check) use the
Phase 2 engine port (advisor_engine.model.build and advisor_engine.brain_check.check).
"""

import json
import math
import re
from datetime import date, timedelta
from pathlib import Path

import pytest

from advisor_engine import books as U
from advisor_engine import brain_check, model
from advisor_engine.company import vocab

FIX = Path(__file__).parent / "fixtures"
QB = FIX / "qb"
MANIFEST = json.loads((QB / "manifest.json").read_text())
NOW = MANIFEST["now"]
CASES = {c["id"]: c for c in MANIFEST["reads"]}


def data_of(example):
    return json.loads((FIX / "skeleton" / example / "data.json").read_text())


HS, BS = "home-services", "barbershop"
DATA = {HS: data_of(HS), BS: data_of(BS)}
BRAIN = {ex: json.loads((FIX / "skeleton" / ex / "brain.json").read_text()) for ex in (HS, BS)}
UNIT_WORDS = {c["example"]: c["unit_words"] for c in MANIFEST["reads"]}


def text_of(case_id):
    # bytes, so the generated CRLF line ends reach the reader unchanged
    return (QB / CASES[case_id]["file"]).read_bytes().decode("utf-8")


def read(text, name, example=HS):
    return U.read(text, name, unit_words=UNIT_WORDS[example])


def read_case(case_id):
    c = CASES[case_id]
    return U.read(text_of(case_id), c["name"], unit_words=c["unit_words"])


def near(a, b, tol=0.01, msg=""):
    assert abs(a - b) <= tol, f"{msg} expected {b} got {a}"


def slots_of(reads):
    out = {}
    for r in reads:
        assert r["ok"], f"{r['name']}: {r.get('error')}"
        out[r["kind"]] = {"name": r["name"], "report": r["report"], "detail": r["detail"],
                          "rows": r["rows"], "data": r["data"]}
    return out


def read_all(example, style):
    return [read_case(f"{example}-{style}-{k}") for k in ("pnl", "balance", "ar", "ap", "sales")]


def jdump(o):
    return json.dumps(o, ensure_ascii=False)


