def _totals(S):
    m = {}
    for rw in S["rows"]:
        k = S["weeks"][rw[0]] + "|" + S["units"][rw[1]] + "|" + S["offerings"][rw[2]]["name"]
        q, a = m.get(k, (0, 0))
        m[k] = (q + rw[3], a + rw[4])
    return m


