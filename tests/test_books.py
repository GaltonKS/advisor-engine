def test_putting_the_files_into_the_snapshot_leaves_the_original_alone():
    base = data_of(HS)
    before = json.dumps(base, sort_keys=True)
    A = U.apply(base, slots_of(read_all(HS, "qbo")), now=NOW, system="quickbooks")
    assert json.dumps(base, sort_keys=True) == before, "the original snapshot is untouched"
    assert A["slots"] == ["pnl", "balance", "sales", "ar", "ap"]
    assert A["still"] == [], "the sales detail showed the customer, so the shares are filled from it"
    D = A["data"]
    assert D["customers"] and D["customers"]["count"] > 0 and D["customers"]["system"] == "quickbooks"
    assert D["meta"]["sample"] is False, "all of the core reports are the owner's, so it is no longer sample"
    assert D["meta"]["uploaded"]["partSample"] is False
    assert D["meta"]["asOf"] == base["balance"]["asOf"]
    assert any(re.search("CSV export", s["api"]) and re.search("Profit", s["report"]) for s in D["sources"])
    assert not any(re.search("Profit", s["report"]) and not re.search("CSV export", s["api"]) for s in D["sources"]), \
        "each file replaces the old source line"
    cash0 = next(f for f in D["facts"] if f["k"] == "cash0")
    assert cash0["v"] == base["balance"]["cash"]
    assert cash0["confirmed"] is False
    assert re.search(r"your file bs\.csv", cash0["src"])


def test_putting_the_files_into_the_snapshot_the_model_reads_it():
    """JS, same apply as above (home-services, qbo): with M0 = FIS.build(DATA, BRAIN) and
    M1 = FIS.build(A.data, BRAIN), M1 has as many units as M0 with the same names, the
    same total sales a month (sum of units' .mo, within $0.50), M1.coverage.ratio within
    5% of 1 (the detail ties to the books), every offering's .cost equal to M0's (1e-9),
    and FIS.check(BRAIN, A.data) has no check at level "fix"."""
    base, brain = data_of(HS), BRAIN[HS]
    # the reads take the brain's unit words, as the JS ctx() does with FIS.vocab
    V = vocab(brain)
    assert UNIT_WORDS[HS] == [V["unit"], V["units"]]
    D = U.apply(base, slots_of(read_all(HS, "qbo")), now=NOW, system="quickbooks")["data"]
    M0, M1 = model.build(base, brain), model.build(D, brain)
    assert len(M1["units"]) == len(M0["units"])
    near(sum(u["mo"] for u in M1["units"]), sum(u["mo"] for u in M0["units"]), 0.5, "sales a month")
    assert [u["name"] for u in M1["units"]] == [u["name"] for u in M0["units"]]
    assert M1["coverage"] and abs(M1["coverage"]["ratio"] - 1) < 0.05, \
        f"detail ties to the books: {M1['coverage'] and M1['coverage']['ratio']}"
    for o in M1["offerings"]:
        b = next(x for x in M0["offerings"] if x["name"] == o["name"])
        near(o["cost"], b["cost"], 1e-9, "direct cost kept for " + o["name"])
    bad = [c for c in brain_check.check(brain, D) if c["level"] == "fix"]
    assert bad == [], json.dumps(bad, default=str)


